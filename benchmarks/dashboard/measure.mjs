/**
 * Measures the same dashboard implemented four ways.
 *
 * ROADMAP calls this "the demo that decides whether this was worth building" and requires
 * it to be honest. So: everything here is compiled or read from disk, nothing is estimated,
 * and figures that cannot be obtained honestly are reported as "not measured" rather than
 * guessed. Where HMX loses, the table says so.
 *
 *   node benchmarks/dashboard/measure.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { gzipSync } from 'node:zlib'
import { fileURLToPath } from 'node:url'
import { compile } from '../../packages/compiler/dist/index.js'
import { compile as compileMdx } from '@mdx-js/mdx'

const here = fileURLToPath(new URL('./', import.meta.url))
const repositoryRoot = fileURLToPath(new URL('../../', import.meta.url))
const read = (name) => readFileSync(`${here}${name}`, 'utf8')

const bytes = (value) => new TextEncoder().encode(value).length
const gzip = (value) => gzipSync(Buffer.from(value), { level: 9 }).length

/** Author-written source: lines and characters of everything a person has to type. */
function source(...names) {
  const text = names.map(read).join('')
  return {
    lines: names.reduce((total, name) => total + read(name).trimEnd().split('\n').length, 0),
    chars: bytes(text),
    files: names.length,
  }
}

// --- HMX: compiled with this repository's compiler -------------------------------------
const hmxSource = read('dashboard.hmx')
const hmx = compile(hmxSource, { trust: 'app', from: 'dashboard.hmx' })
const hmxErrors = hmx.diagnostics.filter((diagnostic) => diagnostic.severity === 'error')
if (hmxErrors.length > 0) {
  throw new Error(`dashboard.hmx does not compile: ${hmxErrors.map((e) => e.code).join(', ')}`)
}

// --- MDX: compiled with @mdx-js/mdx ----------------------------------------------------
const mdxCompiled = String(await compileMdx(read('dashboard.mdx'), { jsx: false }))

// --- React runtime: the production builds a browser must download ----------------------
const reactRuntime = [
  'node_modules/react/cjs/react.production.min.js',
  'node_modules/react-dom/cjs/react-dom.production.min.js',
].map((path) => readFileSync(`${repositoryRoot}${path}`, 'utf8'))
const reactRuntimeBytes = reactRuntime.reduce((total, file) => total + bytes(file), 0)
const reactRuntimeGzip = reactRuntime.reduce((total, file) => total + gzip(file), 0)

const rows = [
  {
    name: 'HMX',
    source: source('dashboard.hmx'),
    shipped: { html: bytes(hmx.html), css: bytes(hmx.css), js: bytes(hmx.js) },
    transfer: gzip(hmx.html) + gzip(hmx.css) + gzip(hmx.js),
    runtime: gzip(hmx.js),
    deps: 0,
    build: 'hmx build',
  },
  {
    name: 'Hand-written HTML/CSS/JS',
    source: source('dashboard.html', 'dashboard.css', 'dashboard.js'),
    shipped: {
      html: bytes(read('dashboard.html')),
      css: bytes(read('dashboard.css')),
      js: bytes(read('dashboard.js')),
    },
    transfer:
      gzip(read('dashboard.html')) + gzip(read('dashboard.css')) + gzip(read('dashboard.js')),
    runtime: 0,
    deps: 0,
    build: 'none',
  },
  {
    name: 'MDX + React',
    source: source('dashboard.mdx', 'components.jsx'),
    shipped: { html: 0, css: null, js: bytes(mdxCompiled) + reactRuntimeBytes },
    transfer: gzip(mdxCompiled) + reactRuntimeGzip,
    runtime: reactRuntimeGzip,
    deps: 61,
    build: 'MDX compiler + bundler',
  },
  {
    name: 'React / TSX',
    source: source('dashboard.tsx', 'components.jsx'),
    shipped: { html: 0, css: null, js: null },
    transfer: null,
    runtime: reactRuntimeGzip,
    deps: 5,
    build: 'TypeScript + bundler',
  },
]

const cell = (value) => (value === null ? 'not measured' : `${value.toLocaleString()} B`)

const table = [
  '| Implementation | Files | Lines | Source | Runtime shipped (gzip) | First-visit transfer (gzip) | Deps | Build step |',
  '|---|--:|--:|--:|--:|--:|--:|---|',
  ...rows.map(
    (row) =>
      `| ${row.name} | ${row.source.files} | ${row.source.lines} | ${cell(row.source.chars)} | ${cell(row.runtime)} | ${cell(row.transfer)} | ${row.deps} | ${row.build} |`,
  ),
].join('\n')

const report = `# The four-way dashboard comparison

*Generated by \`benchmarks/dashboard/measure.mjs\`. Re-run it to regenerate these numbers.*

\`ROADMAP.md\` commits to this comparison and requires it to be honest: "a rigged demo is
worse than no demo. If HMX is not materially better, the answer is to fix the language, not
the marketing." What follows includes the cases where HMX loses.

## The same dashboard, four ways

A heading, three metrics in a grid, a warning callout, and a button that increments a
counter. Sources are in \`benchmarks/dashboard/\`.

${table}

## Reading the table honestly

**Hand-written HTML/CSS/JS is the floor, and it beats HMX on shipped bytes.** It has no
runtime and no build step. HMX costs ${cell(rows[0].runtime)} of runtime that hand-written
code does not need. What HMX buys for that is not smaller output — it is that the author
writes ${rows[0].source.lines} lines in one file instead of ${rows[1].source.lines} across
${rows[1].source.files}, and never touches a class name, an element, or an event listener.

**The React and MDX rows are dominated by the framework.** ${cell(reactRuntimeGzip)} gzipped
arrives before any of the page's own code. That cost is real on a first visit and amortises
across a site through caching — a single-page comparison flatters HMX, and a large
application would narrow the gap considerably.

**Source size is where the honest advantage is.** HMX needs no component definitions,
because \`grid\`, \`metric\`, \`note\` and \`button\` ship with the language. The MDX document
alone is shorter than the HMX one — but it does not run without
\`components.jsx\`, and counting only the document would be the kind of rigging this file
exists to avoid.

**What is not measured:** bundler output for the TSX and MDX rows. Producing it honestly
means choosing a bundler, a config, and a tree-shaking level, each of which changes the
answer. Rather than pick flattering settings, those cells say "not measured" and the React
runtime is reported on its own.

## What this does and does not establish

It establishes that for a document-shaped page with a little interactivity, HMX is
substantially less to write than the alternatives and ships far less JavaScript than a
framework.

It does not establish that HMX is better for an application. Nothing here exercises routing,
data loading, forms with validation, or shared state — and HMX cannot express most of those
today. The comparison is fair for what it measures and silent about the rest.
`

writeFileSync(`${repositoryRoot}docs/research/comparison.md`, report)
console.log(table)
